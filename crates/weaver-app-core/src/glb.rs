//! Optional, CPU-only loading of self-contained static GLB assets.
//!
//! The default scene (or first scene) is flattened into triangle-list meshes.
//! Node transforms are baked into positions and inverse-transpose normals;
//! mirrored nodes have their winding corrected. No axis, unit, origin, or
//! attachment convention is imposed. Bounds cover the referenced, baked vertices.
//! Instances have identity transforms and fresh handles, ready to merge into an
//! application's assets and scene.
//!
//! Only core geometry, UV0, `COLOR_0`, and opaque base color are rendered. Missing
//! normals are generated by area-weighted averaging at shared source vertices.
//! Embedded PNG/JPEG base-color images become RGBA8, with alpha forced opaque as
//! required by glTF's OPAQUE mode. UVs and image rows are not flipped. Base-color
//! images larger than [`GlbOptions::max_texture_dimension`] are downsampled with
//! aspect ratio preserved (never upscaled). Triangle filtering averages encoded
//! color values, not linear-light values; this approximation is reported in a
//! warning. PBR maps, double-sided materials, and sampler settings produce
//! warnings rather than pretending that the current renderer implements them.
//!
//! Unsupported features include URIs (including data URIs), required extensions,
//! compressed geometry/textures, sparse/matrix accessors, animation, skinning,
//! morph targets, non-triangle lists, and alpha mask/blend materials. There is no
//! filesystem, network, GPU, animation, or material-pipeline work here.
//!
//! Fixed safety budgets are intentionally conservative: 128 MiB input, 8 MiB
//! JSON, 4,096 nodes, depth 128, 1,000,000 vertices / 6,000,000 indices per
//! primitive, 4,000,000 vertices / 12,000,000 indices of traversal work, 8,192-pixel
//! source image dimensions, 256 MiB per source RGBA8 image, a 512 MiB decoder
//! allocation budget, 64,000,000 attribute scalar values of traversal work, and
//! 256 MiB total output data. Returned textures default to at most 2,048 pixels
//! per dimension; the configurable output cap cannot exceed 4,096. Conversion
//! and resizing require additional bounded CPU temporaries, so the decoder
//! budget is not a peak-memory guarantee. Encoded source bytes are never changed.
//! These CPU limits do not guarantee that an asset fits a particular GPU.

