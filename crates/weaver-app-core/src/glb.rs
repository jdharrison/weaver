const MAX_INPUT_BYTES: usize = 128 * 1024 * 1024;
const MAX_JSON_BYTES: usize = 8 * 1024 * 1024;
const MAX_RECORDS: usize = 16_384;
const MAX_NODES: usize = 4_096;
const MAX_NODE_LINKS: usize = 8_192;
const MAX_DEPTH: usize = 128;
const MAX_IMAGES: usize = 256;
const MAX_TEXTURE_DIMENSION: u32 = 4_096;
const MAX_SOURCE_TEXTURE_DIMENSION: u32 = 8_192;
const MAX_SOURCE_IMAGE_BYTES: usize = 256 * 1024 * 1024;
const MAX_DECODER_BYTES: usize = 512 * 1024 * 1024;
const MAX_OUTPUT_BYTES: usize = 256 * 1024 * 1024;
const MAX_PRIMITIVE_VERTICES: usize = 1_000_000;
const MAX_PRIMITIVE_INDICES: usize = 6_000_000;
const MAX_WORK_VERTICES: usize = 4_000_000;
const MAX_WORK_INDICES: usize = 12_000_000;
const MAX_WORK_VALUES: usize = 64_000_000;
const CHUNK_VERTICES: usize = u16::MAX as usize + 1;

/// Texture output policy; source decoding retains fixed safety limits.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct GlbOptions {
    /// Maximum returned base-color texture width/height, in `1..=4096`.
    ///
    /// Defaults to 2048. Larger images are downsampled with Triangle filtering in
    /// encoded color space, preserving aspect ratio to the nearest smaller pixel
    /// (with a minimum of one pixel per dimension). Smaller images are unchanged.
    pub max_texture_dimension: u32,
}

impl Default for GlbOptions {
    fn default() -> Self {
        Self {
            max_texture_dimension: 2_048,
        }
    }
}

/// Flattened static model, with all handles local to this load and safe to merge.
#[derive(Clone, Debug)]
pub struct GlbModel {
    /// CPU-side meshes and decoded base-color textures.
    pub assets: AppAssets,
    /// One identity-transformed instance per mesh chunk.
    pub instances: Vec<MeshInstance>,
    /// Minimum referenced vertex position after imported node transforms.
    pub bounds_min: Vec3,
    /// Maximum referenced vertex position after imported node transforms.
    pub bounds_max: Vec3,
    /// Material/attribute approximations and ignored optional features.
    pub warnings: Vec<String>,
}

/// An invalid, unsupported, or over-budget GLB asset.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum GlbError {
    /// Malformed GLB/glTF data, invalid ranges, or invalid attribute values.
    Invalid(String),
    /// A feature cannot be represented by this static loader/current renderer.
    Unsupported(String),
    /// A documented resource budget was exceeded.
    LimitExceeded(&'static str),
}

impl fmt::Display for GlbError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Invalid(message) => write!(f, "invalid GLB: {message}"),
            Self::Unsupported(message) => write!(f, "unsupported GLB: {message}"),
            Self::LimitExceeded(budget) => write!(f, "GLB limit exceeded: {budget}"),
        }
    }
}

impl std::error::Error for GlbError {}

pub(crate) fn invalid(message: impl Into<String>) -> GlbError {
    GlbError::Invalid(message.into())
}

pub(crate) fn limit(value: usize, maximum: usize, budget: &'static str) -> Result<(), GlbError> {
    if value > maximum {
        Err(GlbError::LimitExceeded(budget))
    } else {
        Ok(())
    }
}

/// Load a self-contained static GLB without performing any I/O or GPU work.
///
/// Imported transforms are baked; model recentering, orientation, scale, and
/// placement remain application policy. Large primitives are losslessly
/// reindexed into meshes of at most 65,536 vertices sharing texture handles.
/// Base-color textures are downsampled to at most 2048 pixels per dimension;
/// use [`load_glb_with_options`] to choose another output cap.
///
/// # Errors
///
/// Returns [`GlbError::Invalid`] for malformed or non-finite data,
/// [`GlbError::Unsupported`] for features outside the documented static subset,
/// and [`GlbError::LimitExceeded`] when a resource budget is exceeded.
pub fn load_glb(bytes: &[u8]) -> Result<GlbModel, GlbError> {
    load_glb_with_options(bytes, &GlbOptions::default())
}

/// Load a static GLB with an explicit base-color texture output policy.
///
/// Like [`load_glb`], this performs no I/O and never modifies the encoded source.
/// Only base-color images are decoded; ignored PBR maps remain unallocated.
///
/// # Errors
///
/// Returns the same errors as [`load_glb`], plus [`GlbError::Invalid`] if
/// `options.max_texture_dimension` is outside `1..=4096`. Options are validated
/// before parsing or decoding any input.
pub fn load_glb_with_options(bytes: &[u8], options: &GlbOptions) -> Result<GlbModel, GlbError> {
    if !(1..=MAX_TEXTURE_DIMENSION).contains(&options.max_texture_dimension) {
        return Err(invalid(format!(
            "max_texture_dimension must be in 1..={MAX_TEXTURE_DIMENSION}"
        )));
    }
    limit(bytes.len(), MAX_INPUT_BYTES, "input bytes")?;
    // gltf 1.4 subtracts 12 from this field without checking for underflow.
    // Validate only the envelope here; gltf owns all GLB/JSON parsing.
    if bytes.len() < 12 {
        return Err(invalid("truncated GLB header"));
    }
    let declared = u32::from_le_bytes([bytes[8], bytes[9], bytes[10], bytes[11]]);
    if declared as usize != bytes.len() || !bytes.len().is_multiple_of(4) {
        return Err(invalid(
            "GLB header length does not match the aligned input",
        ));
    }
    let glb = gltf::binary::Glb::from_slice(bytes).map_err(|e| invalid(e.to_string()))?;
    limit(glb.json.len(), MAX_JSON_BYTES, "JSON bytes")?;
    let chunk_bytes = 20 + glb.json.len() + glb.bin.as_ref().map_or(0, |bin| 8 + bin.len());
    if chunk_bytes != bytes.len()
        || !glb.json.len().is_multiple_of(4)
        || glb
            .bin
            .as_ref()
            .is_some_and(|bin| !bin.len().is_multiple_of(4))
    {
        return Err(invalid("unexpected trailing data or unaligned GLB chunks"));
    }
    let root: gltf::json::Root =
        gltf::json::deserialize::from_slice(&glb.json).map_err(|e| invalid(e.to_string()))?;
    validate_root(&root)?;
    // Validate references/enums before calling any gltf accessors that unwrap them.
    let document = Document::from_json(root).map_err(|e| invalid(e.to_string()))?;
    let blob = glb
        .bin
        .as_deref()
        .ok_or_else(|| invalid("missing BIN chunk"))?;
    let data = validate_storage(&document, blob)?;
    validate_static_content(&document)?;
    let scene = document
        .default_scene()
        .or_else(|| document.scenes().next())
        .ok_or_else(|| invalid("no scene"))?;

    let mut loader = Loader {
        data,
        options: *options,
        model: GlbModel {
            assets: AppAssets::default(),
            instances: Vec::new(),
            bounds_min: Vec3::splat(f32::INFINITY),
            bounds_max: Vec3::splat(f32::NEG_INFINITY),
            warnings: Vec::new(),
        },
        image_handles: vec![None; document.images().len()],
        seen_materials: HashSet::new(),
        output_bytes: 0,
        work_vertices: 0,
        work_indices: 0,
        work_values: 0,
    };
    for extension in document.extensions_used() {
        loader.model.warnings.push(format!(
            "Optional extension {extension} is ignored; only core glTF fallback data is used."
        ));
    }

    // Iterative traversal bounds stack usage and rejects cycles/multiple parents.
    let mut visited = vec![false; document.nodes().len()];
    let mut stack: Vec<_> = scene
        .nodes()
        .map(|node| (node, DMat4::IDENTITY, 1))
        .collect();
    stack.reverse();
    while let Some((node, parent, depth)) = stack.pop() {
        limit(depth, MAX_DEPTH, "node depth")?;
        if std::mem::replace(&mut visited[node.index()], true) {
            return Err(invalid("selected scene contains a cycle or repeated node"));
        }
        let world = parent * node_matrix(&node)?;
        if !world.is_finite() {
            return Err(invalid("non-finite accumulated node transform"));
        }
        if let Some(mesh) = node.mesh() {
            let linear = DMat3::from_cols(
                world.x_axis.truncate(),
                world.y_axis.truncate(),
                world.z_axis.truncate(),
            );
            let determinant = linear.determinant();
            if !determinant.is_finite() || determinant == 0.0 {
                return Err(invalid("singular or unrepresentable node transform"));
            }
            let normals = linear.inverse().transpose();
            if !normals.is_finite() {
                return Err(invalid("unrepresentable normal transform"));
            }
            for primitive in mesh.primitives() {
                loader.primitive(&primitive, world, normals, determinant < 0.0)?;
            }
        }
        let start = stack.len();
        stack.extend(node.children().map(|child| (child, world, depth + 1)));
        stack[start..].reverse();
    }
    if loader.model.instances.is_empty() {
        return Err(invalid(
            "selected scene contains no nonempty triangle meshes",
        ));
    }
    Ok(loader.model)
}

fn validate_root(root: &gltf::json::Root) -> Result<(), GlbError> {
    validate_root_mode(root, false)
}

pub(crate) fn validate_root_mode(root: &gltf::json::Root, animated: bool) -> Result<(), GlbError> {
    // Check u64 quantities before gltf converts them to usize (also on WASM32).
    let bounded_bytes = |value: u64| -> Result<(), GlbError> {
        if value > MAX_INPUT_BYTES as u64 {
            Err(GlbError::LimitExceeded("declared buffer bytes/offset"))
        } else {
            Ok(())
        }
    };
    limit(root.nodes.len(), MAX_NODES, "nodes")?;
    limit(root.scenes.len(), 256, "scenes")?;
    limit(root.images.len(), MAX_IMAGES, "images")?;
    limit(root.textures.len(), 512, "textures")?;
    limit(root.materials.len(), 2_048, "materials")?;
    limit(root.extensions_used.len(), 64, "extensions")?;
    limit(root.extensions_required.len(), 64, "required extensions")?;
    for count in [
        root.accessors.len(),
        root.buffer_views.len(),
        root.meshes.len(),
        root.samplers.len(),
        root.cameras.len(),
        root.meshes.iter().map(|mesh| mesh.primitives.len()).sum(),
    ] {
        limit(count, MAX_RECORDS, "document records/primitives")?;
    }
    let links = root
        .nodes
        .iter()
        .map(|node| node.children.as_ref().map_or(0, Vec::len))
        .sum::<usize>()
        + root
            .scenes
            .iter()
            .map(|scene| scene.nodes.len())
            .sum::<usize>();
    limit(links, MAX_NODE_LINKS, "node links")?;
    if let Some(extension) = root.extensions_required.first() {
        return Err(GlbError::Unsupported(format!(
            "required extension {extension}"
        )));
    }
    for extension in &root.extensions_used {
        if matches!(
            extension.as_str(),
            "KHR_draco_mesh_compression"
                | "EXT_meshopt_compression"
                | "KHR_texture_basisu"
                | "EXT_texture_webp"
                | "MSFT_texture_dds"
        ) {
            return Err(GlbError::Unsupported(format!(
                "compressed data ({extension})"
            )));
        }
    }
    if !animated && !root.animations.is_empty() {
        return Err(GlbError::Unsupported(
            "animations (static assets only)".into(),
        ));
    }
    if !animated && (!root.skins.is_empty() || root.nodes.iter().any(|node| node.skin.is_some())) {
        return Err(GlbError::Unsupported(
            "skinning (static assets only)".into(),
        ));
    }
    if root.nodes.iter().any(|node| node.weights.is_some())
        || root.meshes.iter().any(|mesh| {
            mesh.weights.is_some() || mesh.primitives.iter().any(|p| p.targets.is_some())
        })
    {
        return Err(GlbError::Unsupported(
            "morph targets/weights (static assets only)".into(),
        ));
    }
    for buffer in &root.buffers {
        if buffer.uri.is_some() {
            return Err(GlbError::Unsupported(
                "buffer URIs (including data URIs)".into(),
            ));
        }
        bounded_bytes(buffer.byte_length.0)?;
    }
    if root.buffers.len() != 1 {
        return Err(invalid("a GLB must contain exactly one embedded buffer"));
    }
    for image in &root.images {
        if image.uri.is_some() {
            return Err(GlbError::Unsupported(
                "image URIs (including data URIs)".into(),
            ));
        }
        // gltf's minimal validation does not enforce these prerequisites;
        // Image::source() would unwrap them even for an unused image.
        if image.buffer_view.is_none() {
            return Err(invalid("embedded image has no buffer view"));
        }
        let mime = image
            .mime_type
            .as_ref()
            .ok_or_else(|| invalid("embedded image has no MIME type"))?;
        image_format(&mime.0)?;
    }
    for view in &root.buffer_views {
        bounded_bytes(view.byte_length.0)?;
        bounded_bytes(view.byte_offset.unwrap_or_default().0)?;
    }
    for accessor in &root.accessors {
        if accessor.sparse.is_some() {
            return Err(GlbError::Unsupported("sparse accessors".into()));
        }
        bounded_bytes(accessor.byte_offset.unwrap_or_default().0)?;
        if accessor.count.0 == 0 {
            return Err(invalid("zero-count accessor"));
        }
        if accessor.count.0 > MAX_PRIMITIVE_INDICES as u64 {
            return Err(GlbError::LimitExceeded("accessor count"));
        }
    }
    Ok(())
}

fn validate_storage<'a>(document: &Document, blob: &'a [u8]) -> Result<&'a [u8], GlbError> {
    validate_storage_mode(document, blob, false)
}

pub(crate) fn validate_storage_mode<'a>(
    document: &Document,
    blob: &'a [u8],
    animated: bool,
) -> Result<&'a [u8], GlbError> {
    let buffer = document
        .buffers()
        .next()
        .ok_or_else(|| invalid("missing buffer"))?;
    let length = buffer.length();
    if length == 0 || length > blob.len() || blob.len() - length > 3 {
        return Err(invalid(
            "declared buffer length does not match the BIN chunk",
        ));
    }
    let data = &blob[..length];
    for view in document.views() {
        let end = view.offset().checked_add(view.length());
        if view.length() == 0 || end.is_none_or(|end| end > length) {
            return Err(invalid(format!(
                "buffer view {} exceeds the declared buffer",
                view.index()
            )));
        }
        if let Some(stride) = view.stride()
            && (!(4..=252).contains(&stride) || !stride.is_multiple_of(4))
        {
            return Err(invalid("invalid buffer-view stride"));
        }
    }
    for accessor in document.accessors() {
        if matches!(
            accessor.dimensions(),
            Dimensions::Mat2 | Dimensions::Mat3 | Dimensions::Mat4
        ) && (!animated
            || accessor.dimensions() != Dimensions::Mat4
            || accessor.data_type() != DataType::F32
            || accessor.normalized())
        {
            return Err(GlbError::Unsupported(
                "matrix accessors other than float MAT4 inverse binds".into(),
            ));
        }
        let view = accessor
            .view()
            .ok_or_else(|| invalid("accessor has no buffer view"))?;
        let size = accessor.size();
        let component_size = accessor.data_type().size();
        let stride = view.stride().unwrap_or(size);
        // Counts are positive and bounded before this arithmetic or any reader.
        let end = (accessor.count() - 1)
            .checked_mul(stride)
            .and_then(|span| span.checked_add(accessor.offset()))
            .and_then(|end| end.checked_add(size));
        if stride < size
            || !stride.is_multiple_of(component_size)
            || !accessor.offset().is_multiple_of(component_size)
            || !(view.offset() + accessor.offset()).is_multiple_of(component_size)
            || end.is_none_or(|end| end > view.length())
        {
            return Err(invalid(format!(
                "accessor {} has an invalid range/alignment/stride",
                accessor.index()
            )));
        }
    }
    for image in document.images() {
        match image.source() {
            gltf::image::Source::View { view, mime_type } => {
                if view.stride().is_some() {
                    return Err(invalid("an image buffer view must not have a stride"));
                }
                image_format(mime_type)?;
            }
            gltf::image::Source::Uri { .. } => {
                return Err(GlbError::Unsupported("image URIs".into()));
            }
        }
    }
    Ok(data)
}

fn validate_static_content(document: &Document) -> Result<(), GlbError> {
    for mesh in document.meshes() {
        for primitive in mesh.primitives() {
            if primitive.mode() != gltf::mesh::Mode::Triangles {
                return Err(GlbError::Unsupported(
                    "only triangle-list primitives are supported".into(),
                ));
            }
            if primitive
                .attributes()
                .any(|(semantic, _)| matches!(semantic, Semantic::Joints(_) | Semantic::Weights(_)))
            {
                return Err(GlbError::Unsupported("skinning attributes".into()));
            }
        }
    }
    for material in document.materials() {
        if material.alpha_mode() != gltf::material::AlphaMode::Opaque {
            return Err(GlbError::Unsupported("alpha MASK/BLEND materials".into()));
        }
    }
    Ok(())
}

pub(crate) fn node_matrix(node: &gltf::Node<'_>) -> Result<DMat4, GlbError> {
    if let gltf::scene::Transform::Decomposed { rotation, .. } = node.transform() {
        let length_squared = rotation.iter().map(|v| f64::from(*v).powi(2)).sum::<f64>();
        if !length_squared.is_finite() || (length_squared - 1.0).abs() > 0.001 {
            return Err(invalid("node rotation is not a unit quaternion"));
        }
    }
    let matrix = Mat4::from_cols_array_2d(&node.transform().matrix()).as_dmat4();
    if !matrix.is_finite()
        || matrix.x_axis.w != 0.0
        || matrix.y_axis.w != 0.0
        || matrix.z_axis.w != 0.0
        || matrix.w_axis.w != 1.0
    {
        return Err(invalid("node transform must be finite and affine"));
    }
    Ok(matrix)
}

pub(crate) fn validate_primitive(primitive: &Primitive<'_>) -> Result<(usize, usize), GlbError> {
    let positions = primitive
        .get(&Semantic::Positions)
        .ok_or_else(|| invalid("missing POSITION"))?;
    let count = positions.count();
    limit(count, MAX_PRIMITIVE_VERTICES, "primitive vertices")?;
    for (semantic, accessor) in primitive.attributes() {
        if accessor.count() != count {
            return Err(invalid("primitive attribute counts differ from POSITION"));
        }
        let valid = match semantic {
            Semantic::Positions | Semantic::Normals => {
                accessor.dimensions() == Dimensions::Vec3
                    && accessor.data_type() == DataType::F32
                    && !accessor.normalized()
            }
            Semantic::TexCoords(0) => {
                accessor.dimensions() == Dimensions::Vec2 && color_or_uv_type(&accessor)
            }
            Semantic::Colors(0) => {
                matches!(accessor.dimensions(), Dimensions::Vec3 | Dimensions::Vec4)
                    && color_or_uv_type(&accessor)
            }
            _ => true, // Not read; storage and counts were still validated.
        };
        if !valid {
            return Err(invalid(format!(
                "invalid type/normalization for {semantic:?}"
            )));
        }
    }
    let index_count = if let Some(indices) = primitive.indices() {
        if indices.dimensions() != Dimensions::Scalar
            || !matches!(
                indices.data_type(),
                DataType::U8 | DataType::U16 | DataType::U32
            )
            || indices.normalized()
            || indices.view().is_some_and(|view| view.stride().is_some())
        {
            return Err(invalid("indices must be tightly packed unsigned scalars"));
        }
        indices.count()
    } else {
        count
    };
    limit(index_count, MAX_PRIMITIVE_INDICES, "primitive indices")?;
    if index_count == 0 || !index_count.is_multiple_of(3) {
        return Err(invalid(
            "triangle-list index/vertex count must be a nonzero multiple of three",
        ));
    }
    Ok((count, index_count))
}

fn color_or_uv_type(accessor: &Accessor<'_>) -> bool {
    match accessor.data_type() {
        DataType::F32 => !accessor.normalized(),
        DataType::U8 | DataType::U16 => accessor.normalized(),
        _ => false,
    }
}

#[derive(Clone, Copy)]
struct Material {
    color: [f32; 4],
    texture: Option<SpriteHandle>,
}

pub(crate) struct Loader<'a> {
    data: &'a [u8],
    options: GlbOptions,
    pub(crate) model: GlbModel,
    image_handles: Vec<Option<SpriteHandle>>,
    seen_materials: HashSet<Option<usize>>,
    output_bytes: usize,
    work_vertices: usize,
    work_indices: usize,
    work_values: usize,
}

impl<'a> Loader<'a> {
    pub(crate) fn animated(data: &'a [u8], image_count: usize) -> Self {
        Self {
            data,
            options: GlbOptions::default(),
            model: GlbModel {
                assets: AppAssets::default(),
                instances: Vec::new(),
                bounds_min: Vec3::splat(f32::INFINITY),
                bounds_max: Vec3::splat(f32::NEG_INFINITY),
                warnings: Vec::new(),
            },
            image_handles: vec![None; image_count],
            seen_materials: HashSet::new(),
            output_bytes: 0,
            work_vertices: 0,
            work_indices: 0,
            work_values: 0,
        }
    }

    pub(crate) fn animated_primitive(
        &mut self,
        primitive: &Primitive<'_>,
        skin: Option<&[weaver_render_wgpu::SkinVertex]>,
    ) -> Result<(), GlbError> {
        self.primitive_inner(primitive, DMat4::IDENTITY, DMat3::IDENTITY, false, skin)
    }

    fn charge_output(&mut self, bytes: usize) -> Result<(), GlbError> {
        self.output_bytes = self
            .output_bytes
            .checked_add(bytes)
            .ok_or(GlbError::LimitExceeded("output bytes"))?;
        limit(self.output_bytes, MAX_OUTPUT_BYTES, "output bytes")
    }

    pub(crate) fn primitive(
        &mut self,
        primitive: &Primitive<'_>,
        world: DMat4,
        normal_matrix: DMat3,
        mirrored: bool,
    ) -> Result<(), GlbError> {
        self.primitive_inner(primitive, world, normal_matrix, mirrored, None)
    }

    fn primitive_inner(
        &mut self,
        primitive: &Primitive<'_>,
        world: DMat4,
        normal_matrix: DMat3,
        mirrored: bool,
        skin: Option<&[weaver_render_wgpu::SkinVertex]>,
    ) -> Result<(), GlbError> {
        let (vertex_count, index_count) = validate_primitive(primitive)?;
        self.work_vertices += vertex_count;
        self.work_indices += index_count;
        limit(
            self.work_vertices,
            MAX_WORK_VERTICES,
            "total vertex processing",
        )?;
        limit(
            self.work_indices,
            MAX_WORK_INDICES,
            "total index processing",
        )?;
        for (_, accessor) in primitive.attributes() {
            let values = accessor
                .count()
                .checked_mul(accessor.dimensions().multiplicity())
                .and_then(|values| self.work_values.checked_add(values))
                .ok_or(GlbError::LimitExceeded("total attribute processing"))?;
            limit(values, MAX_WORK_VALUES, "total attribute processing")?;
            self.work_values = values;
        }
        let material = self.material(&primitive.material())?;
        let data = self.data;
        let reader = primitive.reader(move |_| Some(data));
        let mut vertices = Vec::with_capacity(vertex_count);
        for position in reader
            .read_positions()
            .ok_or_else(|| invalid("unreadable POSITION"))?
        {
            let position = DVec3::from_array(position.map(f64::from));
            if !position.is_finite() {
                return Err(invalid("non-finite POSITION"));
            }
            let position = world.transform_point3(position).as_vec3();
            if !position.is_finite() {
                return Err(invalid("baked POSITION is not representable as f32"));
            }
            vertices.push(Vertex {
                position: position.to_array(),
                normal: [0.0; 3],
                color: [1.0; 4],
                uv: [0.0; 2],
            });
        }
        if vertices.len() != vertex_count {
            return Err(invalid("POSITION reader count mismatch"));
        }
        let has_normals = primitive.get(&Semantic::Normals).is_some();
        if has_normals {
            let normals = reader
                .read_normals()
                .ok_or_else(|| invalid("unreadable NORMAL"))?;
            for (vertex, normal) in vertices.iter_mut().zip(normals) {
                let normal = DVec3::from_array(normal.map(f64::from));
                if !normal.is_finite() {
                    return Err(invalid("non-finite NORMAL"));
                }
                vertex.normal = (normal_matrix * normal)
                    .try_normalize()
                    .ok_or_else(|| invalid("zero or unrepresentable NORMAL"))?
                    .as_vec3()
                    .to_array();
            }
        }
        if primitive.get(&Semantic::TexCoords(0)).is_some() {
            let uvs = reader
                .read_tex_coords(0)
                .ok_or_else(|| invalid("unreadable TEXCOORD_0"))?;
            for (vertex, uv) in vertices.iter_mut().zip(uvs.into_f32()) {
                if !uv.iter().all(|value| value.is_finite()) {
                    return Err(invalid("non-finite TEXCOORD_0"));
                }
                vertex.uv = uv;
            }
        } else if material.texture.is_some() {
            return Err(invalid("base-color texture requires TEXCOORD_0"));
        }
        if primitive.get(&Semantic::Colors(0)).is_some() {
            let colors = reader
                .read_colors(0)
                .ok_or_else(|| invalid("unreadable COLOR_0"))?;
            for (vertex, mut color) in vertices.iter_mut().zip(colors.into_rgba_f32()) {
                if !color
                    .iter()
                    .all(|value| value.is_finite() && (0.0..=1.0).contains(value))
                {
                    return Err(invalid("COLOR_0 must be finite and in [0, 1]"));
                }
                color[3] = 1.0; // OPAQUE ignores all alpha sources.
                vertex.color = color;
            }
        }
        let mut ignored_attributes = false;
        for (semantic, accessor) in primitive.attributes() {
            if !matches!(
                semantic,
                Semantic::Positions
                    | Semantic::Normals
                    | Semantic::TexCoords(0)
                    | Semantic::Colors(0)
                    | Semantic::Joints(0..=1)
                    | Semantic::Weights(0..=1)
            ) {
                // Validate ignored float attributes too, without hand-decoding data.
                validate_finite_attribute(accessor, data)?;
                ignored_attributes = true;
            }
        }
        if ignored_attributes {
            self.model.warnings.push("Only POSITION, NORMAL, TEXCOORD_0 and COLOR_0 are imported; other vertex attributes are ignored.".into());
        }
        let mut indices: Vec<u32> = if primitive.indices().is_some() {
            reader
                .read_indices()
                .ok_or_else(|| invalid("unreadable indices"))?
                .into_u32()
                .collect()
        } else {
            let end =
                u32::try_from(vertex_count).map_err(|_| GlbError::LimitExceeded("vertex count"))?;
            (0..end).collect()
        };
        if indices.len() != index_count
            || indices.iter().any(|&index| index as usize >= vertex_count)
        {
            return Err(invalid(
                "index count mismatch or index outside POSITION range",
            ));
        }
        if mirrored {
            for triangle in indices.as_chunks_mut::<3>().0 {
                triangle.swap(1, 2);
            }
        }
        if !has_normals {
            let fallback = generate_normals(&mut vertices, &indices);
            self.model.warnings.push("Missing normals were generated by area-weighted averaging at shared source vertices.".into());
            if fallback {
                self.model.warnings.push(
                    "Degenerate/cancelling triangles or unused vertices needed a fallback normal."
                        .into(),
                );
            }
        }
        self.chunks(&vertices, &indices, material, skin)
    }

    fn material(&mut self, material: &gltf::Material<'_>) -> Result<Material, GlbError> {
        let pbr = material.pbr_metallic_roughness();
        let mut color = pbr.base_color_factor();
        if !color
            .iter()
            .all(|value| value.is_finite() && (0.0..=1.0).contains(value))
        {
            return Err(invalid("base-color factor must be finite and in [0, 1]"));
        }
        color[3] = 1.0;
        let base_texture = pbr.base_color_texture();
        if base_texture
            .as_ref()
            .is_some_and(|info| info.tex_coord() != 0)
        {
            return Err(GlbError::Unsupported(
                "base-color textures using UV sets other than UV0".into(),
            ));
        }
        if self.seen_materials.insert(material.index()) {
            if pbr.metallic_roughness_texture().is_some()
                || material.normal_texture().is_some()
                || material.occlusion_texture().is_some()
                || material.emissive_texture().is_some()
                || material.emissive_factor() != [0.0; 3]
                || material.index().is_some()
            {
                self.model.warnings.push(format!(
                    "Material {:?}: base color only; metallic/roughness factors/maps, normal, occlusion and emissive properties are not rendered.",
                    material.index()
                ));
            }
            if material.double_sided() {
                self.model.warnings.push(format!(
                    "Material {:?}: doubleSided is not represented; the renderer still culls back faces.", material.index()
                ));
            }
            if base_texture
                .as_ref()
                .is_some_and(|info| info.texture().sampler().index().is_some())
            {
                self.model.warnings.push("glTF sampler settings are not imported; base-color textures use the renderer's repeat/filter defaults.".into());
            }
        }
        let texture = base_texture
            .map(|info| self.image(&info.texture().source()))
            .transpose()?;
        Ok(Material { color, texture })
    }

    fn image(&mut self, image: &gltf::Image<'_>) -> Result<SpriteHandle, GlbError> {
        if let Some(handle) = self.image_handles[image.index()] {
            return Ok(handle);
        }
        let gltf::image::Source::View { view, mime_type } = image.source() else {
            return Err(GlbError::Unsupported("image URIs".into()));
        };
        // Every view was checked against the declared buffer before any readers.
        let data = self.data;
        let encoded = &data[view.offset()..view.offset() + view.length()];
        let format = image_format(mime_type)?;
        let (source_width, source_height) = image_reader(encoded, format)
            .into_dimensions()
            .map_err(|e| image_error(image.index(), &e))?;
        rgba_length(source_width, source_height)?;
        let (width, height) = texture_dimensions(
            source_width,
            source_height,
            self.options.max_texture_dimension,
        );
        let length = rgba_length(width, height)?;
        // Charge only retained output, not the larger source decoding temporary.
        self.charge_output(length)?;
        let decoded = image_reader(encoded, format)
            .decode()
            .map_err(|e| image_error(image.index(), &e))?;
        if (decoded.width(), decoded.height()) != (source_width, source_height) {
            return Err(invalid("decoded image dimensions mismatch"));
        }
        // Discard OPAQUE alpha before filtering, without allocating a full-sized
        // RGBA8 conversion for RGB JPEGs. Conversion to RGB8 consumes the decoder
        // output; it does not composite transparent pixels against a background.
        let source = decoded.into_rgb8();
        let output = if (width, height) == (source_width, source_height) {
            source
        } else {
            let resized = image::imageops::resize(
                &source,
                width,
                height,
                image::imageops::FilterType::Triangle,
            );
            drop(source);
            self.model.warnings.push(format!(
                "Base-color image {} resized from {source_width}x{source_height} to {width}x{height} using Triangle filtering in encoded color space (not linear-light).",
                image.index()
            ));
            resized
        };
        let rgba = image::DynamicImage::ImageRgb8(output)
            .into_rgba8()
            .into_raw();
        if rgba.len() != length {
            return Err(invalid("decoded image length mismatch"));
        }
        let handle = SpriteHandle::new();
        self.model.assets.textures.push(TextureAsset {
            handle,
            width,
            height,
            rgba,
        });
        self.image_handles[image.index()] = Some(handle);
        Ok(handle)
    }

    fn chunks(
        &mut self,
        source: &[Vertex],
        indices: &[u32],
        material: Material,
        skin: Option<&[weaver_render_wgpu::SkinVertex]>,
    ) -> Result<(), GlbError> {
        let mut skin_vertices = Vec::new();
        let mut remap = HashMap::<u32, u16>::new();
        let mut vertices = Vec::new();
        let mut output_indices = Vec::new();
        for triangle in indices.as_chunks::<3>().0 {
            let mut needed = triangle
                .iter()
                .enumerate()
                .filter(|&(corner, index)| {
                    !remap.contains_key(index) && !triangle[..corner].contains(index)
                })
                .count();
            if vertices.len() + needed > CHUNK_VERTICES {
                self.finish_chunk(
                    std::mem::take(&mut vertices),
                    std::mem::take(&mut output_indices),
                    material,
                    skin.map(|_| std::mem::take(&mut skin_vertices)),
                )?;
                remap.clear();
                needed = triangle
                    .iter()
                    .enumerate()
                    .filter(|&(corner, index)| !triangle[..corner].contains(index))
                    .count();
            }
            // Charge before extending output vectors, including duplicated seam vertices.
            self.charge_output(
                needed
                    * (size_of::<Vertex>()
                        + skin.map_or(0, |_| size_of::<weaver_render_wgpu::SkinVertex>()))
                    + 3 * size_of::<u16>(),
            )?;
            for &source_index in triangle {
                let index = if let Some(&index) = remap.get(&source_index) {
                    index
                } else {
                    let index = u16::try_from(vertices.len())
                        .map_err(|_| invalid("chunk vertex overflow"))?;
                    let vertex = source[source_index as usize];
                    let position = Vec3::from_array(vertex.position);
                    self.model.bounds_min = self.model.bounds_min.min(position);
                    self.model.bounds_max = self.model.bounds_max.max(position);
                    vertices.push(vertex);
                    if let Some(skin) = skin {
                        skin_vertices.push(skin[source_index as usize]);
                    }
                    remap.insert(source_index, index);
                    index
                };
                output_indices.push(index);
            }
        }
        self.finish_chunk(
            vertices,
            output_indices,
            material,
            skin.map(|_| skin_vertices),
        )
    }

    fn finish_chunk(
        &mut self,
        vertices: Vec<Vertex>,
        indices: Vec<u16>,
        material: Material,
        skin: Option<Vec<weaver_render_wgpu::SkinVertex>>,
    ) -> Result<(), GlbError> {
        limit(
            self.model.assets.meshes.len() + 1,
            MAX_RECORDS,
            "mesh chunks",
        )?;
        let handle = MeshHandle::new();
        let mut asset = MeshAsset::new(handle, vertices, indices);
        asset.skin = skin;
        self.model.assets.meshes.push(asset);
        let mut instance = MeshInstance::new(handle, RenderTransform::IDENTITY);
        instance.texture = material.texture;
        instance.color = material.color;
        self.model.instances.push(instance);
        Ok(())
    }
}

fn validate_finite_attribute(accessor: Accessor<'_>, data: &[u8]) -> Result<(), GlbError> {
    if accessor.data_type() != DataType::F32 {
        return Ok(());
    }
    let finite = match accessor.dimensions() {
        Dimensions::Scalar => gltf::accessor::Iter::<f32>::new(accessor, |_| Some(data))
            .is_some_and(|mut values| values.all(f32::is_finite)),
        Dimensions::Vec2 => gltf::accessor::Iter::<[f32; 2]>::new(accessor, |_| Some(data))
            .is_some_and(|mut values| values.all(|v| v.into_iter().all(f32::is_finite))),
        Dimensions::Vec3 => gltf::accessor::Iter::<[f32; 3]>::new(accessor, |_| Some(data))
            .is_some_and(|mut values| values.all(|v| v.into_iter().all(f32::is_finite))),
        Dimensions::Vec4 => gltf::accessor::Iter::<[f32; 4]>::new(accessor, |_| Some(data))
            .is_some_and(|mut values| values.all(|v| v.into_iter().all(f32::is_finite))),
        _ => false, // Matrix accessors were rejected before any readers.
    };
    if finite {
        Ok(())
    } else {
        Err(invalid("unreadable or non-finite vertex attribute"))
    }
}

fn generate_normals(vertices: &mut [Vertex], indices: &[u32]) -> bool {
    // f64 avoids overflow when valid f32 positions have large magnitudes.
    let mut sums = vec![DVec3::ZERO; vertices.len()];
    for triangle in indices.as_chunks::<3>().0 {
        let [a, b, c] = [
            triangle[0] as usize,
            triangle[1] as usize,
            triangle[2] as usize,
        ];
        let position = |i: usize| Vec3::from_array(vertices[i].position).as_dvec3();
        let normal = (position(b) - position(a)).cross(position(c) - position(a));
        for index in [a, b, c] {
            sums[index] += normal;
        }
    }
    let mut fallback = false;
    for (vertex, sum) in vertices.iter_mut().zip(sums) {
        vertex.normal = sum
            .try_normalize()
            .unwrap_or_else(|| {
                fallback = true;
                DVec3::Y
            })
            .as_vec3()
            .to_array();
    }
    fallback
}

fn image_error(index: usize, error: &image::ImageError) -> GlbError {
    match error {
        image::ImageError::Limits(_) => GlbError::LimitExceeded("image decoder limits"),
        _ => invalid(format!("image {index}: {error}")),
    }
}

fn image_format(mime: &str) -> Result<image::ImageFormat, GlbError> {
    match mime {
        "image/png" => Ok(image::ImageFormat::Png),
        "image/jpeg" => Ok(image::ImageFormat::Jpeg),
        _ => Err(GlbError::Unsupported(
            "only embedded PNG/JPEG images are supported".into(),
        )),
    }
}

fn rgba_length(width: u32, height: u32) -> Result<usize, GlbError> {
    if width == 0 || height == 0 {
        return Err(invalid("zero image dimensions"));
    }
    if width > MAX_SOURCE_TEXTURE_DIMENSION || height > MAX_SOURCE_TEXTURE_DIMENSION {
        return Err(GlbError::LimitExceeded("source image dimensions"));
    }
    let length = (width as usize)
        .checked_mul(height as usize)
        .and_then(|pixels| pixels.checked_mul(4))
        .ok_or(GlbError::LimitExceeded("source RGBA image bytes"))?;
    limit(length, MAX_SOURCE_IMAGE_BYTES, "source RGBA image bytes")?;
    Ok(length)
}

fn texture_dimensions(width: u32, height: u32, cap: u32) -> (u32, u32) {
    let longest = width.max(height);
    if longest <= cap {
        return (width, height);
    }
    let scaled =
        |dimension| ((u64::from(dimension) * u64::from(cap) / u64::from(longest)).max(1)) as u32;
    (scaled(width), scaled(height))
}

fn image_reader(data: &[u8], format: image::ImageFormat) -> image::ImageReader<Cursor<&[u8]>> {
    let mut reader = image::ImageReader::with_format(Cursor::new(data), format);
    let mut limits = image::Limits::default();
    limits.max_image_width = Some(MAX_SOURCE_TEXTURE_DIMENSION);
    limits.max_image_height = Some(MAX_SOURCE_TEXTURE_DIMENSION);
    limits.max_alloc = Some(MAX_DECODER_BYTES as u64);
    reader.limits(limits);
    reader
}

